# The official Odoo extension and the language server it runs (odoo/odoo-vscode,
# odoo/odoo-ls). See docs/editor-integration.md for the update procedure.
ODOO_EXTENSION_ID = "Odoo.odoo"

# The OdooLS release this configuration was last reviewed against. Bump it in
# the change that adopts what a review of newer releases found, never alone:
# tools/verify_odools_config.py reports the release notes since this version.
ODOOLS_REVIEWED_VERSION = "1.4.0"

# The only keys emitted per profile: the "minimal config file" of the OdooLS
# documentation. The schema is strict (additionalProperties: false), so an
# unknown key breaks the whole file; these four are in every stable schema on
# record. Keys documented as applying from a given release (the 1.5 JavaScript
# options, semantic-token switches) and template variables are deliberately
# never emitted — they are exactly what changes between releases.
ODOOLS_KEYS: tuple[str, ...] = ("name", "odoo_path", "addons_paths", "python_path")

# OdooLS refuses Odoo below this major ("only supports version 14 and above").
ODOOLS_MIN_ODOO_MAJOR = 14


def odools_versions(cfg: WorkspaceConfig) -> list[str]:
    """The workspace versions the official language server can open."""
    return [v for v in cfg.versions if odoo_major(v) >= ODOOLS_MIN_ODOO_MAJOR]


def _toml_string(value: str) -> str:
    """A TOML basic string. JSON's string escaping is a valid subset of TOML's
    (backslash, quote, control characters, \\uXXXX), so it quotes paths safely."""
    return json.dumps(value, ensure_ascii=False)


def render_odools_toml(cfg: WorkspaceConfig) -> str:
    """The official Odoo language server's configuration: one profile per version.

    The workspace opens only its own root while Odoo lives in the shared cache
    outside it — often in several versions — so OdooLS's zero-config detection
    cannot find it. Each profile states the four facts the generator already
    knows, as absolute paths. Core add-ons are loaded by OdooLS from
    ``odoo_path``, so ``addons_paths`` lists the workspace's own directories only."""
    lines = [
        "# Generated by odoo_dwg — profiles for the official Odoo language server",
        f"# (OdooLS, reviewed against {ODOOLS_REVIEWED_VERSION}). Pick one from the status bar.",
        "# Only the documented minimal keys are set; add your own below if you need more.",
    ]
    skipped = [v for v in cfg.versions if v not in odools_versions(cfg)]
    if skipped:
        lines.append(
            f"# No profile for {', '.join(skipped)}: OdooLS supports Odoo "
            f"{ODOOLS_MIN_ODOO_MAJOR} and above only."
        )
    for inst in cfg.instances():
        if inst.version not in odools_versions(cfg):
            continue
        addons = ", ".join(
            _toml_string(str(path)) for path in cfg.addons_dirs(inst.version, include_core=False)
        )
        values = {
            "name": _toml_string(f"{cfg.name} {inst.version}"),
            "odoo_path": _toml_string(str(cfg.odoo_clone_dir(inst.version))),
            "addons_paths": f"[{addons}]",
            "python_path": _toml_string(str(cfg.venv_dir(inst.version) / "bin" / "python")),
        }
        lines += ["", "[[config]]"] + [f"{key} = {values[key]}" for key in ODOOLS_KEYS]
    return "\n".join(lines) + "\n"


