def _render_step_hook(env: MigrationEnv) -> str:
    """``step_hook``: the operator's SQL around one step, when there is some.

    A client's data can break a migration script no source anticipates: the first
    client's 14.0 step stopped because OpenUpgrade gives every bank statement line
    a journal entry, and some lines belonged to closed banks whose account is
    deprecated. What to do about it is a decision about that client's data, so it
    lives in the environment (``hooks/<version>-pre.sql``, ``-post.sql``), runs in
    one transaction, and is named in the log and the step record. A step with no
    file runs as before."""
    hooks = shlex.quote(str(env.hooks_dir))
    return (
        "# The operator's SQL around a step, from hooks/<version>-pre.sql and -post.sql.\n"
        "step_hook() {\n"
        f'  local file={hooks}/"$1-$2.sql"\n'
        '  [ -f "$file" ] || return 0\n'
        '  psql -X -q -1 -v ON_ERROR_STOP=1 -d "$DB" -f "$file" >/dev/null \\\n'
        '    || die "$1: the $2-step hook $file failed"\n'
        '  echo "[hook] $1 $2: $file"\n'
        '  mark "$1" "hook-$2" "$file"\n'
        "}\n"
    )


def _render_driver_filestore(env: MigrationEnv) -> str:
    """``give_filestore``: the working database's attachments, before any step.

    Odoo looks in ``<data_dir>/filestore/<database>``. With an intake the client's
    files are the reference's, so the working database gets hard links to them —
    no space, and Odoo never rewrites an attachment file in place. Without an
    intake there is nothing to give, and the function says so by doing nothing."""
    if env.intake is None:
        return "give_filestore() { :; }\n"
    q = shlex.quote
    store = env.data_dir / "filestore"
    reference = store / env.intake.reference_database
    return (
        "# The client's attachments, as hard links to the reference's: the steps read\n"
        "# them from the environment's data_dir, which every step's conf names.\n"
        "give_filestore() {\n"
        f'  if [ -d {q(str(reference))} ] && [ ! -e {q(str(store))}/"$DB" ]; then\n'
        f"    mkdir -p {q(str(store))}\n"
        f'    cp -al {q(str(reference))} {q(str(store))}/"$DB" \\\n'
        '      || die "could not give \'$DB\' a filestore"\n'
        f'    echo "[filestore] $DB: hard links to {env.intake.reference_database}\'s attachments"\n'
        "  fi\n"
        "}\n"
    )


def _render_step_preconditions(env: MigrationEnv, version: str) -> str:
    """The step's own code must be on disk before it claims to migrate anything.

    Odoo neither fails nor says anything when ``--upgrade-path`` points at a
    directory that is not there: it simply finds no scripts, and the step would
    be checkpointed as migrated. A clone interrupted mid-way is enough, since
    generation skips a checkout directory that merely exists."""
    if env.uses_legacy_layout(version):
        # The fork *is* Odoo here, so a missing checkout already fails loudly on
        # its own addons_path; its scripts live inside each add-on.
        needed = [(env.openupgrade_clone_dir(version) / "addons", "the OpenUpgrade fork's add-ons")]
    else:
        needed = [
            (env.upgrade_scripts_dir(version), "the OpenUpgrade scripts"),
            (env.openupgrade_clone_dir(version) / "openupgrade_framework", "openupgrade_framework"),
        ]
    lines = [
        f'  [ -d {shlex.quote(str(path))} ] || '
        f'die "{version}: {what} not found at {path} — regenerate the environment"\n'
        for path, what in needed
    ]
    # Coverage again, against the database as it is *now*. The preflight reads
    # the source database once, so a module the chain auto-installs along the way
    # is invisible to it: `partner_firstname_portal` appeared in an OCA
    # repository at 18.0, was auto-installed there, and vanished from the
    # repository at 19.0 — installed, with no code, and nothing had asked.
    sources = " ".join(shlex.quote(str(path)) for path in env.coverage_dirs(version))
    query = (
        # An author spread over lines in its manifest split its row in two, and
        # the second line was checked as a module (16.0 web_search_with_and).
        "SELECT name || E'\\t' || regexp_replace(coalesce(author, ''), '[\\n\\r\\t]+', ' ', 'g') "
        "FROM ir_module_module "
        "WHERE state='installed' ORDER BY name"
    )
    lines.append(
        f'  step_modules=$(psql -X -d "$DB" -tAc {shlex.quote(query)}) '
        f'|| die "{version}: could not list the installed modules"\n'
    )
    lines.append(
        # By the module *name*, which is the first field: the step's rows are
        # "name<TAB>author" and the known list holds names, so comparing whole
        # lines matched nothing and made every module look new.
        '  new_modules=$(printf \'%s\\n\' "$step_modules" | '
        'awk -F\'\\t\' \'NR==FNR {known[$0]; next} $1 != "" && !($1 in known)\' '
        '"$LOGS/known-modules.txt" -)\n'
    )
    lines.append(
        f'  [ -z "$new_modules" ] || ODWG_MODULES_TSV="$new_modules" coverage_step {version} '
        f"{shlex.quote(str(env.apriori_file(version)))} "
        f"{shlex.quote(str(env.addons_custom_dir(version)))} "
        f"{shlex.quote(str(env.decisions_file))} {sources} >/dev/null "
        f'|| die "{version}: a module installed since the preflight resolves nowhere '
        f'(see [coverage] lines above)"\n'
    )
    lines.append(
        f'  ODWG_MODULES_TSV="$step_modules" python_deps_step {version} '
        f"{shlex.quote(str(env.venv_dir(version) / 'bin' / 'python'))} "
        f"{shlex.quote(str(env.apriori_file(version)))} "
        f"{shlex.quote(str(odoo_module_file(env, version)))} {sources} "
        f'|| die "{version}: its modules need Python libraries its venv lacks (see [python] '
        f'lines above) — regenerating the environment offers to install them"\n'
    )
    return "".join(lines)


def _native_step_command(env: MigrationEnv, version: str) -> str:
    """The command that upgrades the working database to one version.

    Two shapes, because OpenUpgrade changed layout at 14. From 14 the scripts sit
    under ``--upgrade-path`` and ``openupgrade_framework`` is loaded. Up to 13 they
    live inside each add-on and neither flag exists — that step runs the fork's own
    ``odoo-bin`` and depends entirely on the add-ons path reaching the fork's
    ``addons``. The path comes from the step's config file, which states it
    explicitly: an inherited or defaulted path that resolves to some other copy of
    Odoo's add-ons skips every add-on migration while the step still succeeds."""
    venv = env.venv_dir(version)
    conf = env.config_file(version)
    log = env.logs_dir / f"{version}.log"
    odoo_bin = env.odoo_bin(version)
    q = shlex.quote
    run = f'{q(f"{venv}/bin/python")} {q(str(odoo_bin))} -c {q(str(conf))} -d "$DB"'
    if env.uses_legacy_layout(version):
        return f"{run} --update all --stop-after-init --logfile={q(str(log))}"
    scripts = env.upgrade_scripts_dir(version)
    return (
        f"{run} --upgrade-path={q(str(scripts))} --update all --stop-after-init "
        f"--load=base,web,openupgrade_framework --logfile={q(str(log))}"
    )


