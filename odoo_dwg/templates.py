def _render_probe_data(probes: list) -> str:
    """One record per probe. `noupdate` so a step's `-u all` cannot rewrite what
    the source version recorded — the record is the evidence."""
    lines = [
        "<?xml version='1.0' encoding='utf-8'?>",
        "<!-- Generated by odoo_dwg. One record per declared expectation. -->",
        "<odoo>",
        '  <data noupdate="1">',
    ]
    for probe in probes:
        lines += [
            f'    <record id="{escape(probe.name)}" model="{tester.PROBE_MODEL}">',
            f'      <field name="name">{escape(probe.name)}</field>',
            f'      <field name="kind">{escape(probe.kind)}</field>',
            f'      <field name="step">{escape(probe.version)}</field>',
            f'      <field name="subject_model">{escape(probe.model)}</field>',
            f'      <field name="subject_field">{escape(probe.field)}</field>',
            f'      <field name="expected_gone" '
            f'eval="{"True" if probe.expected_gone else "False"}"/>',
            # The analysis file's own words: a probe that paraphrased its source
            # would make its own claim unverifiable.
            # Tabs out: the check reads these rows tab-separated, and an
            # analysis line holding one would split into a probe that is not there.
            f'      <field name="source_line">'
            f'{escape(probe.detail.replace(chr(9), " "))}</field>',
            "    </record>",
        ]
    lines += ["  </data>", "</odoo>", ""]
    return "\n".join(lines)


def _render_tester_manifest(probes: list, uncovered: list[str], chain: str) -> str:
    """No menu, no group, no `auto_install`: installing it by accident changes
    nothing a user sees."""
    covered = sorted({probe.kind for probe in probes})
    summary = (
        f"odoo_dwg rehearsal instrument for the {chain} chain — declares what the "
        "OpenUpgrade sources predict, so a step can be asked what it took away. "
        "Not for a production database."
    )
    description = "\n".join(
        [
            f"Generated by odoo_dwg for the {chain} chain.",
            "",
            "Each record of odwg.migration.probe names one upstream subject, the class of",
            "change its step's analysis file declares, and that file's own line.",
            "",
            f"Classes covered ({len(covered)}): " + ", ".join(covered) or "none",
            f"Classes this chain never exercises ({len(uncovered)}): "
            + (", ".join(uncovered) or "none"),
        ]
    )
    return (
        "# Generated by odoo_dwg. Regenerate rather than edit.\n"
        "{\n"
        f'    "name": "odoo_dwg migration tester ({chain})",\n'
        '    "version": "1.0.0",\n'
        '    "category": "Technical",\n'
        '    "license": "LGPL-3",\n'
        f'    "summary": {summary!r},\n'
        f'    "description": """{description}""",\n'
        '    "depends": ["base"],\n'
        '    "data": ["security/ir.model.access.csv", "data/probes.xml"],\n'
        '    "installable": True,\n'
        '    "application": False,\n'
        "}\n"
    )


def render_seed_conf(env: MigrationEnv) -> str:
    """``odoo.conf`` for the source version a demo seed is built on.

    Plain Odoo, not an OpenUpgrade step: the add-ons path is the source's own
    (`source_addons_path`), and mail goes to the local capture like every other
    config this tool writes — demo data contains addresses.
    """
    return "\n".join(
        [
            "[options]",
            f"; Generated by odoo_dwg — demo seed for Odoo {env.source}.",
            f"addons_path = {env.source_addons_path}",
            "",
            f"db_host = {env.db_host}",
            f"db_port = {env.db_port}",
            f"db_user = {env.db_user}",
            "",
            "workers = 0",
            "max_cron_threads = 0",
            "",
            *_smtp_to_capture(),
        ]
    ) + "\n"


def render_seed_demo_sh(env: MigrationEnv, modules: list[str]) -> str:
    """Build a demo database at the source version and dump it for the driver.

    Installed one module at a time, not in one ``-i a,b,c``: Odoo stops at the
    first failure and reports it, and with a single call the operator is told
    only that *something* did not install. One at a time names which — and the
    script stops there rather than dumping a database missing a module the
    rehearsal was meant to exercise.

    The demo flag is **not** passed, and that is the verified answer rather than
    an omission. In 12.0 to 18.0 `--without-demo` carries `my_default=False`
    (`odoo/tools/config.py`), so a database created with `-i` gets Odoo's demo
    data unless the flag disables it. 19.0 rewrote the option — `dest="with_demo"`,
    `type='without_demo'`, and its help now reads "don't install demo data in new
    databases (default)" — so there the default is the opposite. A chain's source
    is always <= 18.0 (`migration_chain` requires source < target <= 19.0), so
    omitting the flag is right for every source this tool accepts; a 19.0 source
    would have to ask for demo data explicitly, and cannot occur.
    """
    q = shlex.quote
    venv = env.venv_dir(env.source)
    odoo_bin = env.odoo_bin(env.source)
    conf = env.config_file(env.source)
    log = env.logs_dir / f"seed-{env.source}.log"
    database = env.source_database
    dump = env.source_dump_file
    run = f'{q(f"{venv}/bin/python")} {q(str(odoo_bin))} -c {q(str(conf))} -d {q(database)}'
    lines = [
        "#!/bin/bash",
        "# Generated by odoo_dwg. Builds a demo source database and dumps it.",
        "set -euo pipefail",
        "",
        'die() { echo "[fail] $*" >&2; exit 1; }',
        "",
        f'DB={q(database)}',
        f'DUMP={q(str(dump))}',
        f'LOG={q(str(log))}',
        "",
        '[ -x "$(command -v createdb)" ] || die "createdb not on PATH"',
        f'[ -x {q(f"{venv}/bin/python")} ] || die "no venv for Odoo {env.source}: generate the environment first"',
        f'[ -r {q(str(odoo_bin))} ] || die "no Odoo {env.source} clone: generate the environment first"',
        "",
        '# A dump the driver may already have checkpoints against is not replaced',
        '# silently; the caller confirms and removes it.',
        '[ -e "$DUMP" ] && die "$DUMP exists — remove it to seed again"',
        "",
        'if psql -X -w -lqt | cut -d\\| -f1 | grep -qw "$DB"; then',
        '  die "database $DB exists — drop it to seed again"',
        "fi",
        'echo "[init] creating $DB"',
        f'createdb -h {q(env.db_host)} -p {int(env.db_port)} -U {q(env.db_user)} "$DB"',
        "",
        # `base` with demo data first: the flag is only read when the database is
        # initialised, so every later module inherits the demo set.
        'echo "[step] installing base with demo data"',
        f'{run} -i base --stop-after-init --logfile="$LOG" '
        '|| die "base did not install — see $LOG"',
    ]
    for module in modules:
        lines += [
            f'echo "[step] installing {module}"',
            f'{run} -i {q(module)} --stop-after-init --logfile="$LOG" '
            f'|| die "{module} did not install — see $LOG"',
        ]
    lines += [
        "",
        'echo "[step] dumping $DB"',
        # -Fc: the format run_migration.sh requires, and the one it checks for.
        # Written beside the target and renamed: a dump interrupted halfway is not
        # a dump, and one left under the real name would be taken for one by the
        # next seed and by the driver.
        f'pg_dump -h {q(env.db_host)} -p {int(env.db_port)} -U {q(env.db_user)} '
        '-Fc -f "$DUMP.tmp" "$DB" || { rm -f "$DUMP.tmp"; die "pg_dump failed"; }',
        'mv -f "$DUMP.tmp" "$DUMP"',
        'echo "[done] $DUMP"',
        'echo "Run the chain with: ./run_migration.sh $DUMP"',
        "",
    ]
    return "\n".join(lines)
