"""Pure text builders for every generated workspace artifact.

Standard-library only, no I/O: each function returns the exact file *content* as a
string, so tests can assert on the rendered text and planners can wrap it in a
``write_text_file_command``. All generated artifacts are **English** (they are
technical and portable); the app's own UI is what gets translated, not these.

Odoo config keys, ``addons_path`` composition, and the source-install flow are
anchored to the official Odoo "Source install" and CLI / ``odoo.conf`` reference
pages (see docs/).
"""

from __future__ import annotations

import json

from .models import InstanceConfig, WorkspaceConfig, odoo_major


def _gevent_port_key(version: str) -> str:
    """Live-chat/bus port key: ``gevent_port`` on Odoo ≥ 16, else ``longpolling_port``."""
    return "gevent_port" if odoo_major(version) >= 16 else "longpolling_port"


def render_odoo_conf(cfg: WorkspaceConfig, version: str) -> str:
    """Render a development ``odoo.conf`` for one instance of the workspace.

    Development posture: ``workers = 0`` (threaded, debugger-friendly), the
    composed ``addons_path``, the derived per-version HTTP port, and a separate
    bus port. Keys are the official ``odoo.conf`` options.
    """
    http_port = cfg.http_port_for(version)
    bus_port = http_port + 1000
    lines = [
        "[options]",
        "; Generated by odoo_dwg — development configuration.",
        f"addons_path = {cfg.addons_path(version)}",
        "",
        "http_interface = 127.0.0.1",
        f"http_port = {http_port}",
        f"{_gevent_port_key(version)} = {bus_port}",
        "",
        "; Development posture: threaded mode so the debugger can attach.",
        "workers = 0",
        "max_cron_threads = 1",
        "dev_mode = reload,qweb,xml",
        "",
        f"db_host = {cfg.db_host}",
        f"db_port = {cfg.db_port}",
        f"db_user = {cfg.db_user}",
        "admin_passwd = admin",
    ]
    return "\n".join(lines) + "\n"


def render_setup_venv_sh(cfg: WorkspaceConfig) -> str:
    """A reproducible bash script that (re)builds every instance venv and installs
    its version-matched requirements from the shared repo cache."""
    header = [
        "#!/usr/bin/env bash",
        "# Generated by odoo_dwg — create/refresh the per-version virtualenvs.",
        "set -euo pipefail",
        "",
        f'WORKSPACE="{cfg.root}"',
        f'REPOS="{cfg.repos_dir}"',
        "",
    ]
    blocks: list[str] = []
    for inst in cfg.instances():
        venv = cfg.venv_dir(inst.version)
        odoo = cfg.odoo_clone_dir(inst.version)
        blocks.append(
            "\n".join(
                [
                    f'echo "[odoo{inst.major}] creating venv {venv}"',
                    f'python3 -m venv "{venv}"',
                    f'"{venv}/bin/pip" install --upgrade pip wheel setuptools',
                    f'"{venv}/bin/pip" install -r "{odoo}/requirements.txt"',
                    "",
                ]
            )
        )
    return "\n".join(header + blocks)


def render_run_sh(cfg: WorkspaceConfig, version: str) -> str:
    """A bash launcher for one instance (venv python + odoo-bin + its conf)."""
    inst = InstanceConfig(cfg.name, version)
    venv = cfg.venv_dir(version)
    odoo = cfg.odoo_clone_dir(version)
    conf = cfg.config_file(version)
    return "\n".join(
        [
            "#!/usr/bin/env bash",
            f"# Generated by odoo_dwg — run the {inst.name} instance.",
            "set -euo pipefail",
            f'exec "{venv}/bin/python" "{odoo}/odoo-bin" -c "{conf}" "$@"',
            "",
        ]
    )


def render_vscode_settings(cfg: WorkspaceConfig) -> str:
    default = cfg.versions[0]
    settings = {
        "python.defaultInterpreterPath": str(cfg.venv_dir(default) / "bin" / "python"),
        "python.terminal.activateEnvironment": True,
        "files.exclude": {"**/__pycache__": True, "**/*.pyc": True},
        "search.exclude": {"**/.venv": True, "**/.repos": True},
    }
    return json.dumps(settings, indent=2) + "\n"


def render_vscode_extensions() -> str:
    recommendations = {
        "recommendations": [
            "ms-python.python",
            "ms-python.debugpy",
            "trinhanhngoc.vscode-odoo",
        ]
    }
    return json.dumps(recommendations, indent=2) + "\n"


def render_vscode_tasks(cfg: WorkspaceConfig) -> str:
    tasks = {
        "version": "2.0.0",
        "tasks": [
            {
                "label": "Setup venvs",
                "type": "shell",
                "command": "bash scripts/setup_venv.sh",
                "problemMatcher": [],
            }
        ]
        + [
            {
                "label": f"Run odoo{odoo_major(v)}",
                "type": "shell",
                "command": f"bash scripts/run-odoo{odoo_major(v)}.sh",
                "problemMatcher": [],
            }
            for v in cfg.versions
        ],
    }
    return json.dumps(tasks, indent=2) + "\n"


def render_vscode_launch(cfg: WorkspaceConfig) -> str:
    configurations = []
    for inst in cfg.instances():
        configurations.append(
            {
                "name": f"Odoo {inst.version} ({inst.name})",
                "type": "debugpy",
                "request": "launch",
                "python": str(cfg.venv_dir(inst.version) / "bin" / "python"),
                "program": str(cfg.odoo_clone_dir(inst.version) / "odoo-bin"),
                "args": ["-c", str(cfg.config_file(inst.version))],
                "console": "integratedTerminal",
                "justMyCode": False,
            }
        )
    return json.dumps({"version": "0.2.0", "configurations": configurations}, indent=2) + "\n"


def render_code_workspace(cfg: WorkspaceConfig) -> str:
    workspace = {
        "folders": [{"path": "."}],
        "settings": {"python.terminal.activateEnvironment": True},
    }
    return json.dumps(workspace, indent=2) + "\n"


def render_workspace_readme(cfg: WorkspaceConfig) -> str:
    """A robust per-workspace README giving any human or AI full context —
    versions, layout, per-version ports/configs, and setup/run commands."""
    version_rows = "\n".join(
        f"| {inst.version} | `{inst.name}` | {cfg.http_port_for(inst.version)} | "
        f"`config/odoo{inst.major}.conf` | `.venv/odoo{inst.major}` |"
        for inst in cfg.instances()
    )
    oca = ", ".join(cfg.oca_repos) if cfg.oca_repos else "(none)"
    return f"""# {cfg.name} — Odoo development workspace

Generated by **odoo_dwg**. This workspace hosts one Odoo Community instance per configured version, each with
its own virtualenv, config, and port. Odoo/OCA source lives in the shared cache at `{cfg.repos_dir}` and is
reused across workspaces.

## Versions

| Version | Instance | HTTP port | Config | Venv |
|---------|----------|-----------|--------|------|
{version_rows}

- OCA repositories: {oca}
- Custom addons: `addons-custom/` · OCA addons (symlinks): `addons-oca/`

## Layout

```
{cfg.name}/
├── addons-custom/        # your modules
├── addons-oca/           # symlinks into the shared OCA cache
├── config/odoo<major>.conf
├── .venv/odoo<major>/    # one venv per version
├── scripts/              # setup_venv.sh, run-odoo<major>.sh
└── {cfg.name}.code-workspace
```

## Setup & run

```bash
# From this workspace directory, on the Linux host:
bash scripts/setup_venv.sh          # create every venv + install requirements
bash scripts/run-odoo{cfg.instances()[0].major}.sh          # launch the {cfg.versions[0]} instance
```

Each instance's `addons_path` is composed of `addons-custom`, the OCA repos, then the shared Odoo `addons`.
Open `{cfg.name}.code-workspace` in VSCode for tasks and debug launch configs.
"""
