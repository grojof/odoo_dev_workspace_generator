def _gevent_port_key(version: str) -> str:
    """Live-chat/bus port key: ``gevent_port`` on Odoo ≥ 16, else ``longpolling_port``."""
    return "gevent_port" if odoo_major(version) >= 16 else "longpolling_port"


def _smtp_to_capture() -> list[str]:
    """Outgoing mail goes to the local capture (Mailpit): shown there when it runs,
    refused when it does not — never delivered. A mail server stored in the
    database takes precedence over these keys; see the mail redirect action."""
    return [
        "; Mail goes to the local capture (Mailpit); never delivered. docs/egress-control.md",
        f"smtp_server = {egress.MAILPIT_SMTP_HOST}",
        f"smtp_port = {egress.MAILPIT_SMTP_PORT}",
    ]


def render_odoo_conf(cfg: WorkspaceConfig, version: str) -> str:
    """Render a development ``odoo.conf`` for one instance of the workspace.

    Development posture: ``workers = 0`` (threaded, debugger-friendly), the
    composed ``addons_path``, the derived per-version HTTP port, and a separate
    bus port. Keys are the official ``odoo.conf`` options.
    """
    http_port = cfg.http_port_for(version)
    bus_port = http_port + 1000
    lines = [
        "[options]",
        "; Generated by odoo_dwg — development configuration.",
        f"addons_path = {cfg.addons_path(version)}",
        "",
        "http_interface = 127.0.0.1",
        f"http_port = {http_port}",
        f"{_gevent_port_key(version)} = {bus_port}",
        "",
        "; Development posture: threaded mode so the debugger can attach.",
        "workers = 0",
        "max_cron_threads = 1",
        # No `reload`: it re-executes the process as soon as watchdog is
        # installed, which detaches the debugger every launch config attaches.
        "dev_mode = qweb,xml",
        "",
        f"db_host = {cfg.db_host}",
        f"db_port = {cfg.db_port}",
        f"db_user = {cfg.db_user}",
        "admin_passwd = admin",
        "",
        *_smtp_to_capture(),
    ]
    return "\n".join(lines) + "\n"


def requirements_install_command(pip: str, requirements: str, version: str) -> str:
    """``pip install -r`` of a branch's requirements, with any substitute applied:
    the dropped project's line is filtered out and its replacement installed in
    the same resolution (see ``models.REQUIREMENT_SUBSTITUTES``)."""
    substitute = requirement_substitute(version)
    if substitute is None:
        return f"{shlex.quote(pip)} install -r {shlex.quote(requirements)}"
    dropped, replacement = substitute
    pattern = shlex.quote(f"^{dropped}([=<>!~; ]|$)")
    return (
        # pipefail: without it only pip's status is seen, so an unreadable
        # requirements file would install the substitute alone and report [OK].
        f"set -o pipefail && grep -v -i -E {pattern} {shlex.quote(requirements)} | "
        f"{shlex.quote(pip)} install -r /dev/stdin {shlex.quote(replacement)}"
    )


def render_setup_venv_sh(
    cfg: WorkspaceConfig,
    interpreters: dict[str, InterpreterChoice] | None = None,
) -> str:
    """A reproducible bash script that (re)builds every instance venv and installs
    its version-matched requirements from the shared repo cache.

    ``interpreters`` must be the same resolved choices the generation plan used:
    a version whose venv the plan builds with a ``uv``-provided interpreter has to
    be rebuilt the same way here, or re-running this script would quietly replace
    it with the host ``python3`` — the exact breakage the support matrix exists to
    prevent."""
    header = [
        "#!/usr/bin/env bash",
        "# Generated by odoo_dwg — create/refresh the per-version virtualenvs.",
        "set -euo pipefail",
        "",
    ]
    blocks: list[str] = []
    for inst in cfg.instances():
        venv = cfg.venv_dir(inst.version)
        odoo = cfg.odoo_clone_dir(inst.version)
        choice = (interpreters or {}).get(inst.version)
        if choice and choice.source == UV_PYTHON and choice.python:
            create = [
                f'# Odoo {inst.version} supports Python {version_support(inst.version).python_range_text()}',
                f"uv venv --seed --no-project --python {shlex.quote(choice.python)} "
                f"{shlex.quote(str(venv))}",
            ]
        else:
            create = [f"python3 -m venv {shlex.quote(str(venv))}"]
        marker = cfg.venv_ready_marker(inst.version)
        blocks.append(
            "\n".join(
                [
                    f"echo {shlex.quote(f'[odoo{inst.major}] creating venv {venv}')}",
                    # Clear the ready marker first and write it last: neither
                    # `uv venv --seed` nor `python3 -m venv` removes it, so a run
                    # that dies between them would leave a half-built venv wearing
                    # the marker that tells every later flow to skip it.
                    f"rm -f {shlex.quote(str(marker))}",
                    *create,
                    f"{shlex.quote(f'{venv}/bin/pip')} install --upgrade pip wheel "
                    f"{shlex.quote(setuptools_requirement(inst.version))}",
                    requirements_install_command(
                        f"{venv}/bin/pip", f"{odoo}/requirements.txt", inst.version
                    ),
                    f"touch {shlex.quote(str(marker))}",
                    "",
                ]
            )
        )
    return "\n".join(header + blocks)


def render_run_sh(cfg: WorkspaceConfig, version: str) -> str:
    """A bash launcher for one instance (venv python + odoo-bin + its conf)."""
    inst = InstanceConfig(cfg.name, version)
    venv = cfg.venv_dir(version)
    odoo = cfg.odoo_clone_dir(version)
    conf = cfg.config_file(version)
    return "\n".join(
        [
            "#!/usr/bin/env bash",
            f"# Generated by odoo_dwg — run the {inst.name} instance.",
            "set -euo pipefail",
            f"exec {shlex.quote(f'{venv}/bin/python')} {shlex.quote(f'{odoo}/odoo-bin')} "
            f'-c {shlex.quote(str(conf))} "$@"',
            "",
        ]
    )


