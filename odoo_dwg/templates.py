def render_vscode_launch(cfg: WorkspaceConfig) -> str:
    configurations = []
    for inst in cfg.instances():
        configurations.append(
            {
                "name": f"Odoo {inst.version} ({inst.name})",
                "type": "debugpy",
                "request": "launch",
                "python": str(cfg.venv_dir(inst.version) / "bin" / "python"),
                "program": str(cfg.odoo_clone_dir(inst.version) / "odoo-bin"),
                "args": ["-c", str(cfg.config_file(inst.version))],
                "console": "integratedTerminal",
                "justMyCode": False,
            }
        )
    return json.dumps({"version": "0.2.0", "configurations": configurations}, indent=2) + "\n"


def render_code_workspace(cfg: WorkspaceConfig) -> str:
    workspace = {
        "folders": [{"path": "."}],
        "settings": {"python.terminal.activateEnvironment": True},
    }
    return json.dumps(workspace, indent=2) + "\n"


def render_workspace_readme(cfg: WorkspaceConfig) -> str:
    """A robust per-workspace README giving any human or AI full context —
    versions, layout, per-version ports/configs, and setup/run commands."""
    version_rows = "\n".join(
        f"| {inst.version} | `{inst.name}` | {cfg.http_port_for(inst.version)} | "
        f"`config/odoo{inst.major}.conf` | `.venv/odoo{inst.major}` |"
        for inst in cfg.instances()
    )
    oca = ", ".join(cfg.oca_repos) if cfg.oca_repos else "(none)"
    return f"""# {cfg.name} — Odoo development workspace

Generated by **odoo_dwg**. This workspace hosts one Odoo Community instance per configured version, each with
its own virtualenv, config, and port. Odoo/OCA source lives in the shared cache at `{cfg.repos_dir}` and is
reused across workspaces.

## Versions

| Version | Instance | HTTP port | Config | Venv |
|---------|----------|-----------|--------|------|
{version_rows}

- OCA repositories: {oca}
- Custom addons: `addons-custom/` · OCA addons (symlinks): `addons-oca/`

## Layout

```
{cfg.name}/
├── addons-custom/        # your modules
├── addons-oca/           # symlinks into the shared OCA cache
├── config/odoo<major>.conf
├── .venv/odoo<major>/    # one venv per version
├── scripts/              # setup_venv.sh, run-odoo<major>.sh
└── {cfg.name}.code-workspace
```

## Setup & run

```bash
# From this workspace directory, on the Linux host:
bash scripts/setup_venv.sh          # create every venv + install requirements
bash scripts/run-odoo{cfg.instances()[0].major}.sh          # launch the {cfg.versions[0]} instance
```

Each instance's `addons_path` is composed of `addons-custom`, the OCA repos, then the shared Odoo `addons`.
Open `{cfg.name}.code-workspace` in VSCode for tasks and debug launch configs.
"""


# --- migration (F3) --------------------------------------------------------


# Overrides applied via ``uv pip install --overrides``: an entry replaces every
# requirement of the same package name during resolution (entries for packages the
# requirements never pull are ignored). Odoo branches 16/17/18 all pin
# gevent==21.8.0 for python_version == '3.10' (the Jammy assumption), but that
# release predates CPython 3.10 (no cp310 wheel) and its sdist no longer compiles
# under modern Cython. The official requirements' own pins for the 3.11 row —
# gevent==22.10.2 + greenlet==2.0.2 — ship cp310 wheels, so we lift to those.
_PY310_OVERRIDES = ("gevent==22.10.2", "greenlet==2.0.2")


def render_migration_overrides(version: str) -> str:
    """Per-version requirements repair for old branches, fed to ``--overrides``.

    Only the Python-3.10 steps need repairs today (see ``_PY310_OVERRIDES``);
    other interpreters resolve their branch's pins to installable wheels/sdists
    (validated on WSL: Odoo 15 on 3.8, Odoo 18 on 3.12)."""
    python, _method = migration_interpreter(version)
    lines = [
        f"# Generated by odoo_dwg — requirements overrides for Odoo {version}"
        f" (Python {python or 'docker'})."
    ]
    if python == "3.10":
        lines.append("# gevent==21.8.0 has no cp310 wheel; lift to the branch's own 3.11 pins.")
        lines.extend(_PY310_OVERRIDES)
    return "\n".join(lines) + "\n"


def render_migration_conf(env: MigrationEnv, version: str) -> str:
    """Per-step ``odoo.conf`` for a migration step (no HTTP — runs stop-after-init)."""
    lines = [
        "[options]",
        f"; Generated by odoo_dwg — OpenUpgrade step to Odoo {version}.",
        f"addons_path = {env.addons_path(version)}",
        "",
        f"db_host = {env.db_host}",
        f"db_port = {env.db_port}",
        f"db_user = {env.db_user}",
        "",
        "workers = 0",
        "max_cron_threads = 0",
    ]
    return "\n".join(lines) + "\n"


def _native_step_command(env: MigrationEnv, version: str) -> str:
    venv = env.venv_dir(version)
    odoo = env.odoo_clone_dir(version)
    conf = env.config_file(version)
    scripts = env.upgrade_scripts_dir(version)
    log = env.logs_dir / f"{version}.log"
    # >= 14 module layout (openupgrade_framework + openupgrade_scripts).
    return (
        f'"{venv}/bin/python" "{odoo}/odoo-bin" -c "{conf}" -d "$DB" '
        f'--upgrade-path="{scripts}" --update all --stop-after-init '
        f'--load=base,web,openupgrade_framework --logfile="{log}"'
    )


def render_docker_step(env: MigrationEnv, version: str) -> str:
    """A ``docker run`` recipe for a step whose Python (3.5/3.6) uv cannot provide
    (Odoo 12/13), against the shared PostgreSQL. Text only — the host provides the
    daemon. The ≤ 13 OpenUpgrade branches are a full Odoo *fork* (own ``odoo-bin``
    at the repo root — verified on branch 13.0), so the container runs the fork's
    odoo-bin from the mounted clone with ``openupgradelib`` installed on the fly;
    ``--upgrade-path``/``openupgrade_framework`` do not exist before 14.0. Running
    a non-``odoo`` command bypasses the image entrypoint, so db flags are explicit.
    TODO: full validation against a real legacy dump (see docs/migration caveats)."""
    major = odoo_major(version)
    ou = env.openupgrade_clone_dir(version)
    # Double quotes so "$DB" expands in the *driver* shell, not the container.
    inner = (
        f'pip3 install --quiet openupgradelib && '
        f'python3 /openupgrade/odoo-bin -d $DB '
        f'--db_host={env.db_host} --db_port={env.db_port} --db_user={env.db_user} '
        f'--update all --stop-after-init'
    )
    return (
        f'docker run --rm --network=host '
        f'-v "{ou}:/openupgrade" '
        f'odoo:{major}.0 '
        f'bash -c "{inner}"'
    )


def _render_preflight_host(env: MigrationEnv) -> str:
    """Bash host-scope preflight: chain tools, PostgreSQL, dump integrity. The
    bash mirror of ``preflight.gather_host_facts`` (see design: the driver must
    stay plain bash, so the checks are rendered, kept in this one function)."""
    lines = [
        "preflight_host() {",
        '  command -v uv >/dev/null 2>&1 || fail "uv not found (needed for the native venvs)"',
    ]
    for version in env.chain():
        if not env.is_native(version):
            image = f"odoo:{odoo_major(version)}.0"
            lines += [
                f'  command -v docker >/dev/null 2>&1 || fail "docker not found (needed for the Odoo {odoo_major(version)} step)"',
                '  docker info >/dev/null 2>&1 || fail "docker daemon not responding (service down or missing docker-group permission)"',
                f'  docker image inspect {image} >/dev/null 2>&1 || fail "image {image} missing (docker pull {image})"',
            ]
    lines += [
        '  psql -tAc "SELECT 1" postgres >/dev/null 2>&1 || fail "PostgreSQL not reachable as $PGUSER@$PGHOST:$PGPORT"',
        '  [ -r "$SRC_DUMP" ] || fail "source dump not readable: $SRC_DUMP"',
        '  pg_restore --list "$SRC_DUMP" >/dev/null 2>&1 || fail "pg_restore cannot list $SRC_DUMP — a custom-format dump (pg_dump -Fc) is required"',
        '  echo "[preflight] host checks passed"',
        "}",
    ]
    return "\n".join(lines)


def _render_preflight_db(env: MigrationEnv) -> str:
    """Bash database-scope preflight, run right after the fresh 00_source restore
    (a resumed database is mid-chain, so the version check only holds there):
    declared-source match from ir_module_module, then per-step addons coverage."""
    source_major = odoo_major(env.source)
    lines = [
        "preflight_db() {",
        '  local base_ver missing=0',
        '  base_ver=$(psql -d "$DB" -tAc "SELECT latest_version FROM ir_module_module WHERE name=\'base\'")',
        f'  case "$base_ver" in {source_major}.*) ;; *) fail "database base version \'$base_ver\' does not match declared source {env.source}";; esac',
        '  modules=$(psql -d "$DB" -tAc "SELECT name FROM ir_module_module WHERE state=\'installed\'")',
    ]
    for version in env.chain():
        if not env.is_native(version):
            lines.append(
                f'  echo "[preflight] coverage not verifiable for {version} (the odoo:{odoo_major(version)}.0 image provides core)"'
            )
            continue
        sources = " ".join(
            f'"{p}"'
            for p in (
                env.addons_custom_dir(version),
                env.addons_oca_dir(version),
                env.openupgrade_clone_dir(version),
                env.odoo_clone_dir(version) / "addons",
                env.odoo_clone_dir(version) / "odoo" / "addons",
            )
        )
        lines += [
            f"  # coverage: step {version}",
            '  for m in $modules; do',
            "    found=0",
            f"    for src in {sources}; do",
            '      [ -d "$src/$m" ] && found=1 && break',
            "    done",
            f'    [ "$found" = 1 ] || {{ echo "[coverage] $m missing for {version} — place it in {env.addons_custom_dir(version)}" >&2; missing=1; }}',
            "  done",
        ]
    lines += [
        '  [ "$missing" = 0 ] || fail "addons coverage incomplete (see [coverage] lines above)"',
        '  echo "[preflight] database checks passed"',
        "}",
    ]
    return "\n".join(lines)


def render_run_migration_sh(env: MigrationEnv) -> str:
    """The checkpointing driver: preflight the host, restore a source dump into a
    working DB (verifying it before step 1), then run each step in order, dumping
    a checkpoint after each success so a re-run resumes from the last good step
    (never touches the source/production database)."""
    header = f"""#!/usr/bin/env bash
# Generated by odoo_dwg — OpenUpgrade migration {env.source} -> {env.target}.
set -euo pipefail

SRC_DUMP="${{1:?usage: run_migration.sh <source-db-custom-format-dump>}}"
DB="{env.working_db}"
export PGHOST="{env.db_host}" PGPORT="{env.db_port}" PGUSER="{env.db_user}"
CK="{env.checkpoints_dir}"
LOGS="{env.logs_dir}"
mkdir -p "$CK" "$LOGS"

fail() {{ echo "[preflight-fail] $1" >&2; exit 1; }}

{_render_preflight_host(env)}

{_render_preflight_db(env)}

have_ck() {{ [ -f "$CK/$1.dump" ]; }}
checkpoint() {{ pg_dump -Fc "$DB" > "$CK/$1.dump"; echo "[checkpoint] $1"; }}

preflight_host

if ! have_ck 00_source; then
  echo "[init] restoring source dump into working DB '$DB'"
  dropdb --if-exists "$DB"
  createdb "$DB"
  pg_restore --no-owner --dbname "$DB" "$SRC_DUMP"
  preflight_db
  checkpoint 00_source
else
  echo "[init] resuming — source checkpoint present"
fi
"""
    steps: list[str] = []
    for version in env.chain():
        if env.is_native(version):
            command = _native_step_command(env, version)
            kind = "native"
        else:
            command = render_docker_step(env, version)
            kind = "docker"
        steps.append(
            f"""
# --- step: upgrade to {version} ({kind}) ---
if have_ck "{version}"; then
  echo "[skip] {version} already migrated"
else
  echo "[step] upgrading to {version} ({kind})"
  {command}
  checkpoint "{version}"
fi"""
        )
    footer = f'\n\necho "[done] migration complete — working DB is now Odoo {env.target}"\n'
    return header + "".join(steps) + footer
