def _render_step_repair(env: MigrationEnv, version: str) -> str:
    """What a step's known OpenUpgrade defect needs, after its post hook.

    OpenUpgrade's 14.0 account post-migration gives every statement line without an
    entry one through the ORM, then computes the lines' ``is_reconciled`` in raw SQL
    with no flush in between, so the ORM's stale values (computed before the suspense
    line existed) are written over it. Lines still in the suspense account end up
    stored as reconciled and the reconciliation screen hides them. Odoo's own
    ``_compute_is_reconciled``, identical in 14.0 and 18.0, recomputes them: only the
    lines stored as reconciled that still have a suspense line. The same run carries the
    SII certificate file the OCA 14.0 migration leaves in the old table. Only for a
    source up to 13.0: from 14.0 every line already has its entry, and the certificate
    model already exists."""
    if version != STATEMENT_LINES_REPAIR_STEP or \
            odoo_major(env.source) > LEGACY_LAYOUT_MAX_MAJOR:
        return ""
    q = shlex.quote
    python = q(f"{env.venv_dir(version)}/bin/python")
    shell = (f'{python} {q(str(env.odoo_bin(version)))} shell -c {q(str(env.config_file(version)))} '
             f'-d "$DB" --no-http --logfile={q(str(env.logs_dir / f"{version}.log"))}')
    return (
        "  # OpenUpgrade 14.0 stores unreconciled statement lines as reconciled (an ORM\n"
        "  # flush over its own SQL); Odoo's own method recomputes them. The OCA 14.0\n"
        "  # SII migration leaves the certificate file behind; it is carried here.\n"
        f"  {shell} <<'ODWG_REPAIR' || die \"{version}: the repairs after the step failed "
        "(statement lines' reconciled flag, SII certificate file)\"\n"
        f"{_STATEMENT_LINES_REPAIR}{_SII_CERTIFICATE_REPAIR}ODWG_REPAIR\n"
        f'  mark "{version}" repair statement-lines-is-reconciled\n'
        f'  mark "{version}" repair sii-certificate-file\n'
    )


#: The client-modules stage's checkpoint and step-record name, after the target step.
def modules_stage(env: MigrationEnv) -> str:
    return f"{env.target}-modules"


def carry_source() -> str:
    """``odoo_dwg/carry.py`` as the driver embeds it: the file itself, so the driver and
    ``migrate modules`` compute the same plan."""
    return resources.files("odoo_dwg").joinpath("carry.py").read_text(encoding="utf-8")


#: Run by the target's Odoo shell: the renames the plan lists, with OpenUpgrade's own
#: library (in every chain venv, since OpenUpgrade requires it). ``merge_modules`` folds a
#: module into one that already exists, so several old modules can share one new name.
_MODULES_RENAME = """\
import json, os
from openupgradelib import openupgrade
with open(os.environ["ODWG_MODULES_PLAN"], encoding="utf-8") as handle:
    plan = json.load(handle)
pairs = [tuple(pair) for pair in plan["renames"]]
if pairs:
    openupgrade.update_module_names(env.cr, pairs, merge_modules=True)
    env.cr.commit()
for old, new in pairs:
    print("[modules] %s -> %s" % (old, new))
"""

#: Run by the same shell once everything is installed: the plan's uninstalls. Odoo also
#: uninstalls whatever depends on them, so a module no decision drops stops it first.
_MODULES_UNINSTALL = """\
import json, os
with open(os.environ["ODWG_MODULES_PLAN"], encoding="utf-8") as handle:
    plan = json.load(handle)
Module = env["ir.module.module"]
wanted = set(plan["updates"]) | set(plan["installs"])
done = set(Module.search([("name", "in", list(wanted)), ("state", "=", "installed")]).mapped("name"))
if wanted - done:
    # Odoo skips a module it cannot load and still exits 0: never uninstall the old
    # modules when what replaces them is not there.
    print("[modules] not installed after the update: %s; nothing uninstalled"
          % ", ".join(sorted(wanted - done)))
    raise SystemExit(1)
modules = Module.search(
    [("name", "in", plan["uninstalls"]), ("state", "in", ("installed", "to upgrade"))])
along = modules.downstream_dependencies() - modules
if along:
    print("[modules] uninstalling %s would also remove %s, which no decision drops or replaces"
          % (", ".join(sorted(modules.mapped("name"))), ", ".join(sorted(along.mapped("name")))))
    raise SystemExit(1)
if modules:
    modules.button_immediate_uninstall()
print("[modules] uninstalled: %s" % (", ".join(sorted(modules.mapped("name"))) or "none"))
"""


def _render_modules_stage(env: MigrationEnv) -> str:
    """The client's modules at the target: renamed, replaced or dropped as decided.

    After the target step the client's old modules are still installed with no code, their
    tables and identifiers intact; that is what a rename needs. The decisions are read when
    the stage runs, through ``carry.py`` embedded verbatim, so editing them needs no
    regeneration. Plain Odoo runs here, without OpenUpgrade's framework: the client's modules
    migrate with their own scripts. The order is the point: renames, then one run that
    updates and installs, then the uninstalls, since an old module can be the only owner of a
    table its replacement adopts."""
    q = shlex.quote
    target = env.target
    stage = modules_stage(env)
    binary = f"{q(f'{env.venv_dir(target)}/bin/python')} {q(str(env.odoo_bin(target)))}"
    args = (f'-c {q(str(env.config_file(target)))} -d "$DB" '
            f'--logfile={q(str(env.logs_dir / f"{stage}.log"))}')
    odoo = f"{binary} {args}"
    shell = f"{binary} shell {args} --no-http"
    sources = " ".join(q(str(p)) for p in env.coverage_dirs(target))
    return f"""
# --- stage: the client's modules at {target} (renamed, replaced, dropped) ---
# carry.py, embedded verbatim: the plan `odoo-dwg migrate modules` prints. It is computed
# once, against the database, so a module the database does not have is only skipped.
carry() {{
  python3 - {q(str(env.decisions_file))} {q(env.source)} {q(target)} "$MODULES_PLAN" {sources} <<'ODWG_CARRY'
{carry_source()}ODWG_CARRY
}}
modules_fail() {{ mark "{stage}" fail "$1"; die "{stage}: $2"; }}
if have_ck "{stage}"; then
  echo "[skip] {stage} already carried"
  mark "{stage}" skip
else
  if [ "$AT_TARGET" != 1 ] && [ -f "$MODULES_DIRTY" ]; then
    # An earlier carry changed the working database and left no checkpoint (it failed,
    # or --redo-modules removed it): only the target checkpoint can be trusted.
    mark - restore "{target}"
    restore_ck "{target}"
    rm -f "$MODULES_DIRTY"
  fi
  installed=$(psql -X -At -d "$DB" -c \\
    "SELECT name FROM ir_module_module WHERE state IN ('installed', 'to upgrade')") \\
    || die "{stage}: could not list the installed modules"
  code=0
  ODWG_INSTALLED="$installed" carry > "$LOGS/{stage}.lists" || code=$?
  if [ "$code" -eq 3 ]; then
    echo "[modules] nothing to carry"
    mark "{stage}" skip "nothing to carry"
  elif [ "$code" -ne 0 ]; then
    modules_fail "$code" "stopped before changing the database (see [modules] lines above)"
  else
    {{ read -r UPDATES; read -r INSTALLS; }} < "$LOGS/{stage}.lists"
    echo "[step] carrying the client's modules at {target}"
    mark "{stage}" start
    # From here the working database is no longer the target checkpoint until this
    # stage writes its own; a run that stops before that restores the target first.
    : > "$MODULES_DIRTY"
    ( step_hook "{stage}" pre ) || modules_fail hook "the pre hook failed"
    ODWG_MODULES_PLAN="$MODULES_PLAN" {shell} <<'ODWG_RENAME' \\
      || modules_fail rename "the renames failed — see the output above and {env.logs_dir}/{stage}.log"
{_MODULES_RENAME}ODWG_RENAME
    mark "{stage}" renamed "$(python3 -c 'import json, sys; print(" ".join("%s>%s" % tuple(p) for p in json.load(open(sys.argv[1]))["renames"]))' "$MODULES_PLAN")"
    if [ -n "$UPDATES$INSTALLS" ]; then
      code=0
      {odoo} ${{UPDATES:+-u "$UPDATES"}} ${{INSTALLS:+-i "$INSTALLS"}} --stop-after-init || code=$?
      [ "$code" -eq 0 ] \\
        || modules_fail "$code" "updating and installing failed — see {env.logs_dir}/{stage}.log"
      mark "{stage}" updated "$UPDATES"
      mark "{stage}" installed "$INSTALLS"
    fi
    ODWG_MODULES_PLAN="$MODULES_PLAN" {shell} <<'ODWG_UNINSTALL' \\
      || modules_fail uninstall "the uninstalls failed or were refused — see [modules] lines above"
{_MODULES_UNINSTALL}ODWG_UNINSTALL
    mark "{stage}" uninstalled "$(python3 -c 'import json, sys; print(" ".join(json.load(open(sys.argv[1]))["uninstalls"]))' "$MODULES_PLAN")"
    ( step_hook "{stage}" post ) || modules_fail hook "the post hook failed"
    neutralise "{stage}"
    checkpoint "{stage}"
    rm -f "$MODULES_DIRTY"
    mark "{stage}" ok
  fi
fi"""


def render_migration_constraints(version: str) -> str | None:
    """Build constraints for a step whose dependencies a current toolchain cannot
    build as pinned, or ``None`` when the step needs none.

    Distinct from the requirements overrides: those change *what* is installed,
    these constrain the environment packages are *built* with. The 13.0 branch
    needs it because ``vatnumber==1.2`` still calls ``use_2to3``, which setuptools
    removed in 58."""
    if odoo_major(version) > LEGACY_LAYOUT_MAX_MAJOR:
        return None
    return (
        f"# Generated by odoo_dwg — build constraints for Odoo {version}.\n"
        "# vatnumber==1.2 uses use_2to3, removed in setuptools 58.\n"
        "setuptools<58\n"
    )


def _render_preflight_host(env: MigrationEnv) -> str:
    """Bash host-scope preflight: chain tools, PostgreSQL, dump integrity. The
    bash mirror of ``preflight.gather_host_facts`` (see design: the driver must
    stay plain bash, so the checks are rendered, kept in this one function)."""
    lines = [
        "preflight_host() {",
        '  command -v uv >/dev/null 2>&1 || fail "uv not found (needed for the native venvs)"',
    ]
    lines += [
        # -X, like every other psql this project runs: `~/.psqlrc` can hold a
        # `\\c otherdb` or a `\\! command`, none of which is visible in the plan.
        '  psql -X -tAc "SELECT 1" postgres >/dev/null 2>&1 || fail "PostgreSQL not reachable as $PGUSER@$PGHOST:$PGPORT"',
        '  [ -r "$SRC_DUMP" ] || fail "source dump not readable: $SRC_DUMP"',
        '  pg_restore --list "$SRC_DUMP" >/dev/null 2>&1 || fail "pg_restore cannot list $SRC_DUMP — a custom-format dump (pg_dump -Fc) is required"',
        '  echo "[preflight] host checks passed"',
        "}",
    ]
    return "\n".join(lines)


def odoo_module_file(env: MigrationEnv, version: str) -> Path:
    """The step's own ``odoo/modules/module.py``: how it reads external dependencies."""
    return Path(env.odoo_bin(version)).parent / "odoo" / "modules" / "module.py"


def _render_python_deps_helper() -> str:
    """``python_deps_step``: what the step's modules declare, checked in its own venv.

    Run by the step's interpreter, as Odoo checks it: the distribution and its
    version, then the import name. Odoo only checks when it upgrades a module,
    minutes into the step; the first client's chain stopped at 13.0 on
    ``unidecode`` that way. Checked before the step, it fails in seconds and names
    the module and the library."""
    return "\n".join([
        "python_deps_step() {",
        '  local version="$1" py="$2" apriori="$3" odoo_module="$4"; shift 4',
        "  \"$py\" - \"$version\" \"$apriori\" \"$odoo_module\" \"$@\" <<'PYDEPS'",
        "import ast, importlib, os, re, sys, warnings",
        "warnings.simplefilter('ignore')  # pkg_resources' deprecation, on every lookup",
        "version, apriori, odoo_module, *sources = sys.argv[1:]",
        "# Odoo 18 parses a dependency with a version or a marker with `packaging`, and",
        "# fails on it when `packaging` is missing: read from the step's own Odoo.",
        "try:",
        "    strict = 'Package `packaging` is required' in open(odoo_module, encoding='utf-8').read()",
        "except OSError:",
        "    strict = False",
        "renames = {}",
        "try:",
        "    tree = ast.parse(open(apriori, encoding='utf-8').read())",
        "except (OSError, ValueError, SyntaxError):",
        "    tree = None",
        "for node in (tree.body if tree is not None else []):",
        "    if isinstance(node, ast.Assign) and {t.id for t in node.targets",
        "            if isinstance(t, ast.Name)} & {'renamed_modules', 'merged_modules'}:",
        "        try:",
        "            value = ast.literal_eval(node.value)",
        "        except (ValueError, TypeError):",
        "            continue",
        "        if isinstance(value, dict):",
        "            renames.update({str(k): str(v) for k, v in value.items()})",
        "def where(name):",
        "    for src in sources:",
        "        if os.path.isdir(os.path.join(src, name)):",
        "            return os.path.join(src, name)",
        "    return None",
        "def declared(path):",
        "    for manifest in ('__manifest__.py', '__openerp__.py'):",
        "        try:",
        "            data = ast.literal_eval(open(os.path.join(path, manifest), encoding='utf-8').read())",
        "        except (OSError, ValueError, SyntaxError, TypeError):",
        "            continue",
        "        external = data.get('external_dependencies') if isinstance(data, dict) else None",
        "        deps = external.get('python') if isinstance(external, dict) else None",
        "        return [d for d in deps if isinstance(d, str)] if isinstance(deps, list) else []",
        "    return []",
        "def packaging(part):",
        "    for base in ('packaging', 'pkg_resources.extern.packaging',",
        "                 'setuptools._vendor.packaging', 'pip._vendor.packaging'):",
        "        try:",
        "            return importlib.import_module(base + '.' + part)",
        "        except Exception:",
        "            continue",
        "    return None",
        "def problem(dep):",
        r"    if strict and not re.fullmatch(r'[\w\-]+', dep):",
        "        try:",
        "            importlib.import_module('packaging.requirements')",
        "        except Exception:",
        "            return 'packaging is not installed, and this Odoo needs it to read it'",
        "    text, _, marker = dep.partition(';')",
        "    markers = packaging('markers')",
        "    if marker.strip() and markers is not None:",
        "        try:",
        "            if not markers.Marker(marker).evaluate():",
        "                return None",
        "        except Exception:",
        "            pass",
        r"    match = re.match(r'\s*([A-Za-z0-9][A-Za-z0-9._-]*)\s*(.*)$', text)",
        "    if not match:",
        "        return None",
        "    name, spec = match.group(1), match.group(2).strip()",
        "    try:",
        "        from importlib import metadata",
        "        installed = metadata.version(name)",
        "    except Exception:",
        "        try:",
        "            importlib.import_module(name)",
        "            return None",
        "        except Exception:",
        "            return 'not installed'",
        "    specifiers = packaging('specifiers')",
        "    if not spec or specifiers is None:",
        "        return None",
        "    try:",
        "        fits = specifiers.SpecifierSet(spec).contains(installed, prereleases=True)",
        "    except Exception:",
        "        return None",
        "    return None if fits else installed + ' installed'",
        "missing = []",
        "for line in os.environ.get('ODWG_MODULES_TSV', '').splitlines():",
        "    name = line.split('\\t')[0].strip()",
        "    if not name:",
        "        continue",
        "    found = where(name) or (where(renames[name]) if renames.get(name) else None)",
        "    for dep in declared(found) if found else []:",
        "        why = problem(dep)",
        "        if why:",
        "            missing.append((os.path.basename(found), dep, why))",
        "for module, dep, why in missing:",
        "    print('[python] %s needs %s for %s: %s' % (module, dep, version, why), file=sys.stderr)",
        "sys.exit(1 if missing else 0)",
        "PYDEPS",
        "}",
    ])


def _render_coverage_helper() -> str:
    """The bash+python helper the driver uses to judge one step's coverage.

    It applies the same rule as ``preflight.gather_coverage``: resolve what
    OpenUpgrade declares renamed or merged before calling anything missing, then
    split what is left by author — Odoo's own dropped code is a warning the
    upgrade handles, anybody else's is the operator's to supply. It reads
    ``apriori.py`` with ``ast`` at run time (never executing it), which is why
    nothing here needs the checkout at render time.

    Exits non-zero only when the blocking class is non-empty.
    """
    return "\n".join(
        [
            "coverage_step() {",
            '  local version="$1" apriori="$2" customdir="$3" decisions="$4"; shift 4',
            # The module list travels in the environment, never on stdin: the
            # heredoc below *is* python's stdin, so anything piped in is lost and
            # the check would silently pass with nothing to check.
            "  python3 - \"$version\" \"$apriori\" \"$customdir\" \"$decisions\" \"$@\" <<'PYCOV'",
            "import ast, json, os, sys",
            "version, apriori, customdir, decisions_file, *sources = sys.argv[1:]",
            "# What the operator decided about modules no step can resolve. Read",
            "# here and not only by the preflight menu action: without it a",
            "# recorded decision was accepted there and refused by this, which",
            "# left the record inert exactly where it mattered.",
            "decided = {}",
            "try:",
            "    with open(decisions_file, encoding=\"utf-8\") as handle:",
            "        data = json.load(handle)",
            "    # The shape `decisions_to_json` writes: a wrapper object, or a bare",
            "    # list for a file written by hand. Reading only one of them made",
            "    # this see nothing in the file the tool itself produces.",
            "    entries = data.get(\"decisions\") if isinstance(data, dict) else data",
            "    for entry in entries if isinstance(entries, list) else []:",
            "        if isinstance(entry, dict) and entry.get(\"module\"):",
            "            decided[entry[\"module\"]] = entry",
            "except (OSError, ValueError, TypeError):",
            "    pass",
            '# Exact spellings only: OCA authors contain "Odoo" and must not pass.',
            'ODOO_AUTHORS = {"odoo s.a.", "odoo sa", "openerp s.a.", "openerp sa", "odoo"}',
            "renames = {}",
            "try:",
            '    tree = ast.parse(open(apriori, encoding="utf-8").read())',
            "except (OSError, ValueError, SyntaxError):",
            '    print("[coverage] %s: no readable apriori.py — renames unknown" % version,',
            "          file=sys.stderr)",
            "    tree = None",
            "if tree is not None:",
            "    for node in tree.body:",
            "        if not isinstance(node, ast.Assign):",
            "            continue",
            "        names = {t.id for t in node.targets if isinstance(t, ast.Name)}",
            '        if not names & {"renamed_modules", "merged_modules"}:',
            "            continue",
            "        try:",
            "            value = ast.literal_eval(node.value)",
            "        except (ValueError, TypeError):",
            "            continue",
            "        if isinstance(value, dict):",
            "            renames.update({str(k): str(v) for k, v in value.items()",
            "                            if isinstance(v, str)})",
            "def resolves(name):",
            "    return any(os.path.isdir(os.path.join(src, name)) for src in sources)",
            "",
            "def where(name):",
            "    for src in sources:",
            "        if os.path.isdir(os.path.join(src, name)):",
            "            return os.path.join(src, name)",
            "    return None",
            "",
            "def depends_of(path):",
            "    # One key of a manifest, parsed and never executed. A module that",
            "    # resolves but names a dependency that does not is refused by Odoo",
            "    # at load time — after the chain has already run this far.",
            "    for manifest in (\"__manifest__.py\", \"__openerp__.py\"):",
            "        try:",
            "            with open(os.path.join(path, manifest), encoding=\"utf-8\") as handle:",
            "                data = ast.literal_eval(handle.read())",
            "        except (OSError, ValueError, SyntaxError, TypeError):",
            "            continue",
            "        if isinstance(data, dict) and isinstance(data.get(\"depends\"), list):",
            "            return [d for d in data[\"depends\"] if isinstance(d, str)]",
            "        return []",
            "    return []",
            "",
            "# Nothing to resolve against: report that, rather than calling every",
            "# module missing — including `base`, which cannot be dropped.",
            "if not any(os.path.isdir(src) for src in sources):",
            "    print('[coverage] %s: its sources are not on disk — regenerate the"
            " environment' % version, file=sys.stderr)",
            "    raise SystemExit(1)",
            "blocking, dropped, settled, unmet = [], [], [], []",
            'modules_tsv = os.environ.get("ODWG_MODULES_TSV", "")',
            "if not modules_tsv.strip():",
            '    print("[coverage] %s: no module list to check" % version, file=sys.stderr)',
            "    sys.exit(1)",
            "# The list as the *next* step will see it: a module this step renames",
            "# or absorbs answers to its new name from here on, and the next step's",
            "# apriori.py says nothing about the old one. Checking the original at",
            "# every step reported a module absorbed at 13.0 as missing at 14.0 and",
            "# stopped the run, asking for code that should not exist.",
            "carried = []",
            "for line in modules_tsv.splitlines():",
            '    parts = line.strip().split("\\t")',
            "    name = parts[0] if parts else \"\"",
            '    author = parts[1] if len(parts) > 1 else ""',
            "    # The name the operator's database had, kept beside the current one:",
            "    # a decision is recorded against a module, and a rename does not make",
            "    # it a different module.",
            '    original = parts[2] if len(parts) > 2 else name',
            "    if not name:",
            "        continue",
            "    successor = renames.get(name)",
            '    carried.append("%s\\t%s\\t%s" % (successor or name, author, original))',
            "    found = where(name)",
            "    if found is not None:",
            "        absent = [d for d in depends_of(found) if not resolves(d)]",
            "        if absent:",
            "            unmet.append((name, sorted(absent)))",
            "        continue",
            "    if successor and resolves(successor):",
            "        continue",
            "    # Under any name the module has in this chain: the one the",
            "    # operator started with, the one this step knows it by, or the one",
            "    # it is about to become. They copy whichever they were shown.",
            "    answer = next((decided[a] for a in (name, original, successor)",
            "                   if a and a in decided), None)",
            "    if answer:",
            "        # Applied only because the module resolves nowhere and has no",
            "        # successor that does — the sources are never overruled.",
            "        settled.append((name, answer.get(\"decision\", \"\"), answer.get(\"reason\", \"\")))",
            "    elif author.strip().lower() in ODOO_AUTHORS:",
            "        dropped.append(name)",
            "    else:",
            "        blocking.append(name)",
            "for name in dropped:",
            '    print("[coverage] %s is not in %s and is not renamed — Odoo dropped it; '
            'OpenUpgrade removes it" % (name, version), file=sys.stderr)',
            "for name, decision, reason in settled:",
            '    print("[coverage] %s: %s for %s — as you recorded%s" % (name, decision, version,',
            '          (" (" + reason + ")") if reason else ""), file=sys.stderr)',
            "for name, absent in unmet:",
            '    print("[coverage] %s needs %s for %s, which resolves nowhere"',
            '          % (name, ", ".join(absent), version), file=sys.stderr)',
            "for name in blocking:",
            '    print("[coverage] %s missing for %s — place it in %s" % (name, version, customdir),',
            "          file=sys.stderr)",
            "# stdout carries the list forward; every diagnostic goes to stderr.",
            'print("\\n".join(carried))',
            "sys.exit(1 if blocking or unmet else 0)",
            "PYCOV",
            "}",
        ]
    )


def _render_preflight_db(env: MigrationEnv) -> str:
    """Bash database-scope preflight, run right after the fresh 00_source restore
    (a resumed database is mid-chain, so the version check only holds there):
    declared-source match from ir_module_module, then per-step addons coverage.

    Coverage asks for each module's author as well as its name, because that is
    what separates a core module Odoo dropped (the upgrade removes it) from code
    the step genuinely needs."""
    source_major = odoo_major(env.source)
    lines = [
        _render_coverage_helper(),
        "",
        _render_python_deps_helper(),
        "",
        "preflight_db() {",
        "  local base_ver blocking=0 next_tsv",
        '  base_ver=$(psql -X -d "$DB" -tAc "SELECT latest_version FROM ir_module_module WHERE name=\'base\'") '
        '|| fail "could not query the restored database \'$DB\'"',
        f'  case "$base_ver" in {source_major}.*) ;; *) fail "database base version \'$base_ver\' does not match declared source {env.source}";; esac',
        '  modules_tsv=$(psql -X -d "$DB" -tAc "SELECT name || E\'\\t\' || regexp_replace(coalesce(author, \'\'), \'[\\n\\r\\t]+\', \' \', \'g\') FROM ir_module_module WHERE state=\'installed\' ORDER BY name") '
        '|| fail "could not list the installed modules of \'$DB\'"',
        '  : > "$LOGS/known-modules.txt"',
    ]
    for version in env.chain():
        # The step's own add-ons path, so coverage asks exactly what the step
        # will be able to resolve — including the <= 13 fork layout.
        sources = " ".join(shlex.quote(str(p)) for p in env.coverage_dirs(version))
        apriori = shlex.quote(str(env.apriori_file(version)))
        custom = shlex.quote(str(env.addons_custom_dir(version)))
        decisions = shlex.quote(str(env.decisions_file))
        lines += [
            f"  # coverage: step {version}",
            f'  next_tsv=$(ODWG_MODULES_TSV="$modules_tsv" coverage_step {version} {apriori} '
            f'{custom} {decisions} {sources}) || blocking=1',
            # Kept even when the step reported blocking modules: the later steps
            # still have to be checked, and against the names they will use.
            '  if [ -n "$next_tsv" ]; then modules_tsv="$next_tsv"; fi',
        ]
    lines += [
        # The names the preflight accounted for. A step judges what is *not*
        # here — a module the chain installed along the way, which the source
        # database never had. Anything already accounted for reaches the same
        # verdict twice, so judging it again buys nothing and only widens what a
        # gate lets through.
        '  printf \'%s\\n\' "$modules_tsv" | cut -f1 > "$LOGS/known-modules.txt"',
        '  [ "$blocking" = 0 ] || fail "addons coverage incomplete (see [coverage] lines above)"',
        '  echo "[preflight] database checks passed"',
        "}",
    ]
    return "\n".join(lines)


def render_run_migration_sh(env: MigrationEnv) -> str:
    """The checkpointing driver: preflight the host, restore a source dump into a
    working DB (verifying it before step 1), then run each step in order, dumping
    a checkpoint after each success (never touches the source/production database).

    A re-run resumes from the last good step: the working DB is restored from the
    newest checkpoint before the first pending step, because a failed step leaves
    it half-migrated (OpenUpgrade commits module by module). The run is bound to
    one source dump by its SHA-256, so a different dump is refused instead of
    silently ignored."""
    header = f"""#!/usr/bin/env bash
# Generated by odoo_dwg — OpenUpgrade migration {env.source} -> {env.target}.
set -euo pipefail

SRC_DUMP="${{1:?usage: run_migration.sh <source-db-custom-format-dump> [--redo-modules]}}"
# --redo-modules: run the client-modules stage again, from the target checkpoint.
REDO_MODULES=0
case "${{2:-}}" in
  "") ;;
  --redo-modules) REDO_MODULES=1 ;;
  *) echo "usage: run_migration.sh <source-db-custom-format-dump> [--redo-modules]" >&2; exit 2 ;;
esac
MODULES_CK={shlex.quote(modules_stage(env))}
MODULES_PLAN={shlex.quote(str(env.logs_dir / f"{modules_stage(env)}-plan.json"))}
# Present while the client-modules stage has changed the working database without a
# checkpoint of its own: the stage then starts again from the target checkpoint.
MODULES_DIRTY={shlex.quote(str(env.checkpoints_dir / f"{modules_stage(env)}.dirty"))}
# Whether the working database is known to be exactly at the target checkpoint.
AT_TARGET=0
DB={shlex.quote(env.database)}
export PGHOST={shlex.quote(env.db_host)} PGPORT={int(env.db_port)} PGUSER={shlex.quote(env.db_user)}
CK={shlex.quote(str(env.checkpoints_dir))}
LOGS={shlex.quote(str(env.logs_dir))}
# A checkpoint is a dump of the restored copy of a customer's production
# database, and a log is Odoo's log for it: neither is for other accounts on this
# host to read, whatever the operator's umask and home directory allow.
umask 077
mkdir -p "$CK" "$LOGS"
chmod 700 "$CK" "$LOGS"

fail() {{ echo "[preflight-fail] $1" >&2; exit 1; }}
die() {{ echo "[fail] $1" >&2; exit 1; }}

{_render_preflight_host(env)}

{_render_preflight_db(env)}

# One line per event, appended and never rewritten: a run killed mid-step still
# leaves a readable record, and a watcher can tail it while the chain runs. The
# timestamp is what `journalctl --since/--until` takes, so a step's window can be
# handed to the firewall's journal without guessing where the step began.
#   <when>\t<run>\t<step>\t<event>\t<detail>
STEPS="$LOGS/steps.tsv"
mark() {{ printf '%s\t%s\t%s\t%s\t%s\n' "$(date -Is)" "${{SRC_SHA:0:12}}" "$1" "$2" "${{3:-}}" >> "$STEPS"; }}

have_ck() {{ [ -f "$CK/$1.dump" ]; }}
# Written through a temp file: an interrupted dump must never look like a
# finished checkpoint the next run would trust.
checkpoint() {{
  # Explicitly, not as a && b || c: a failing pg_dump must abort the run instead
  # of leaving an empty .tmp behind while the step reports success.
  if ! pg_dump -Fc "$DB" > "$CK/$1.dump.tmp"; then
    rm -f "$CK/$1.dump.tmp"
    die "checkpoint $1 could not be written"
  fi
  mv "$CK/$1.dump.tmp" "$CK/$1.dump" || die "checkpoint $1 could not be saved"
  echo "[checkpoint] $1"
}}

# Every database this driver leaves behind — each checkpoint, and the migrated one —
# is neutralised: crons off but housekeeping, mail captured, tax, EDI, payment and
# online services out of production, every change recorded inside the database.
# Re-applied at every point, because a step's module updates switch crons back on.
# Nothing here gives production's settings back: that is the operator's action.
NEUTRALISE={shlex.quote(str(env.root / NEUTRALISE_FILE))}
NEUTRAL_CHECK={shlex.quote(str(env.root / NEUTRAL_CHECK_FILE))}
neutralise() {{
  if [ ! -f "$NEUTRALISE" ] || [ ! -f "$NEUTRAL_CHECK" ]; then
    echo "[warn] $NEUTRALISE is missing — regenerate this environment. '$DB' is NOT neutralised." >&2
    return 0
  fi
  psql -X -q -v ON_ERROR_STOP=1 -d "$DB" -f "$NEUTRALISE" >/dev/null \\
    || die "could not neutralise '$DB' ($1)"
  psql -X -q -v ON_ERROR_STOP=1 -d "$DB" -f "$NEUTRAL_CHECK" >/dev/null \\
    || die "'$DB' can still act on the outside after neutralising ($1)"
  echo "[neutralise] $1"
  mark - neutralised "$1"
}}

preflight_host
{_render_driver_filestore(env)}
{_render_step_hook(env)}
restore_ck() {{
  echo "[init] restoring checkpoint $1 into working DB '$DB'"
  dropdb --if-exists "$DB"
  createdb "$DB"
  give_filestore
  pg_restore --no-owner --dbname "$DB" "$CK/$1.dump"
  neutralise "$1"
}}

SRC_SHA=$(sha256sum "$SRC_DUMP" | cut -d' ' -f1)
mark - run-start "{env.source} -> {env.target}"
if ! have_ck 00_source; then
  # A fresh run owns the checkpoint directory: step dumps left by an earlier run
  # belong to another attempt and would be skipped as if they were this one's.
  rm -f "$CK"/*.dump "$CK"/*.dump.tmp "$CK"/*.dirty "$CK/source.sha256"
  mark - restore 00_source
  echo "[init] restoring source dump into working DB '$DB'"
  dropdb --if-exists "$DB"
  createdb "$DB"
  give_filestore
  pg_restore --no-owner --dbname "$DB" "$SRC_DUMP"
  preflight_db
  neutralise 00_source
  echo "$SRC_SHA" > "$CK/source.sha256.tmp" && mv "$CK/source.sha256.tmp" "$CK/source.sha256"
  checkpoint 00_source
else
  # Three states, not two: recorded and equal, recorded and different, or not
  # recorded at all. Calling the third one "another source dump" was false, and
  # the remedy it named threw away every completed step of the chain.
  CK_SHA=$(cat "$CK/source.sha256" 2>/dev/null || true)
  if [ -z "$CK_SHA" ]; then
    die "the checkpoints in $CK do not record which dump they came from.
  If they came from $SRC_DUMP, adopt them with:
    sha256sum \\"$SRC_DUMP\\" | cut -d' ' -f1 > \\"$CK/source.sha256\\"
  If they came from another dump, remove $CK to start over."
  elif [ "$CK_SHA" != "$SRC_SHA" ]; then
    die "checkpoints in $CK came from another source dump — remove that whole directory to start over"
  fi
  if [ "$REDO_MODULES" = 1 ]; then
    # The working database holds the stage's result: the stage restores the target first.
    if have_ck "$MODULES_CK"; then
      rm -f "$CK/$MODULES_CK.dump"
      : > "$MODULES_DIRTY"
    fi
    echo "[init] --redo-modules: the client-modules stage runs again"
  fi
  # A failed step leaves the working DB half-migrated: resume from the newest
  # checkpoint, not from whatever the DB holds now.
  LAST=00_source
  gap=0
  for step in {' '.join(env.chain())}; do
    if [ "$gap" = 0 ] && have_ck "$step"; then
      LAST="$step"
    else
      # Past the first gap nothing is trustworthy: those dumps came from another
      # attempt, and a step after a gap would run on the wrong database.
      gap=1
      rm -f "$CK/$step.dump"
    fi
  done
  # The client-modules stage comes after the target step, and follows the same rule.
  if [ "$gap" = 0 ] && have_ck "$MODULES_CK"; then
    LAST="$MODULES_CK"
  else
    rm -f "$CK/$MODULES_CK.dump"
  fi
  if [ "$LAST" = "{env.target}" ] || [ "$LAST" = "$MODULES_CK" ]; then
    echo "[init] every step already has a checkpoint"
  else
    mark - restore "$LAST"
    restore_ck "$LAST"
  fi
fi
"""
    steps: list[str] = []
    for version in env.chain():
        layout = "legacy layout" if env.uses_legacy_layout(version) else "upgrade-path layout"
        steps.append(
            f"""
# --- step: upgrade to {version} ({layout}) ---
if have_ck "{version}"; then
  echo "[skip] {version} already migrated"
  mark "{version}" skip
else
  echo "[step] upgrading to {version} ({layout})"
  mark "{version}" start
{_render_step_preconditions(env, version)}  step_hook "{version}" pre
  code=0
  {_native_step_command(env, version)} || code=$?
  # `|| code=$?`, not `if ! cmd; then code=$?`: inside the negation `$?` is the
  # status of *not having failed*, which is 0, so every failure was recorded as
  # exit 0 — verified by running the driver against a failing step.
  if [ "$code" -ne 0 ]; then
    mark "{version}" fail "$code"
    die "step {version} failed — see {env.logs_dir}/{version}.log"
  fi
  step_hook "{version}" post
{_render_step_repair(env, version)}  neutralise "{version}"
  checkpoint "{version}"
  mark "{version}" ok
fi"""
        )
    # The target step just ran, or was skipped: only when it ran is the working database
    # known to be exactly at the target checkpoint.
    done = f'  mark "{env.target}" ok\nfi'
    if not steps[-1].endswith(done):
        raise AssertionError("the target step no longer ends where AT_TARGET is set")
    steps[-1] = steps[-1][: -len(done)] + (f'  mark "{env.target}" ok\n  AT_TARGET=1\n  rm -f "$MODULES_DIRTY"\nfi')
    steps.append(_render_modules_stage(env))
    footer = (
        '\n\nmark - run-ok\n'
        f'echo "[done] migration complete — working DB is now Odoo {env.target}"\n'
    )
    return header + "".join(steps) + footer


